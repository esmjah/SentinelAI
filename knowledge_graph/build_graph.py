"""Build the SentinelAI well-integrity knowledge graph for synthetic well W01 (NetworkX).

    python -m knowledge_graph.build_graph       # build, validate, write kg.json

Inputs: catalog.py (engineering content), tag_map.yaml (instrumentation), signatures.yaml
(twin-computed fingerprints, generated by twin_link.py).
"""
from __future__ import annotations

import json
from pathlib import Path

import networkx as nx
import yaml

from .schema import Node, NodeType as N, EdgeType as E, NODE_VIEW, TestSpec, LimitSpec, SCHEMA_VERSION
from . import catalog as C

HERE = Path(__file__).parent


def _add(g, node: Node):
    g.add_node(node.id, type=node.type.value, name=node.name, view=NODE_VIEW[node.type].value, **node.props)


def _link(g, src, dst, etype: E, **props):
    assert src in g and dst in g, f"dangling edge {src} -[{etype.value}]-> {dst}"
    g.add_edge(src, dst, key=etype.value, type=etype.value, **props)


def build_graph(tag_map_path: Path = HERE / "tag_map.yaml",
                signatures_path: Path = HERE / "signatures.yaml") -> nx.MultiDiGraph:
    g = nx.MultiDiGraph(schema_version=SCHEMA_VERSION, name="SentinelAI well-integrity KG (synthetic)")

    # ---------------------------------------------------------------- hierarchy and items
    for nid, t, name, parent, props in C.HIERARCHY:
        _add(g, Node(id=nid, type=N(t), name=name, props=props))
        if parent:
            _link(g, nid, parent, E.PART_OF)
    for nid, name, sub, props in C.ITEMS:
        _add(g, Node(id=nid, type=N.MAINTAINABLE_ITEM, name=name, props=props))
        _link(g, nid, sub, E.PART_OF)
    for nid, name, parent, props, walls in C.VOLUMES:
        _add(g, Node(id=nid, type=N.CONTAINMENT_VOLUME, name=name, props=props))
        _link(g, nid, parent, E.PART_OF)
        for item in walls:
            _link(g, nid, item, E.BOUNDED_BY)
    for nid, t, name, props in C.ZONES:
        _add(g, Node(id=nid, type=N(t), name=name, props=props))
    for a, b in [("W01.RES", "W01.BORE"), ("W01.BORE", "W01.CHK"), ("W01.CHK", "FL-W01"),
                 ("FL-W01", "MAN-P1"), ("MAN-P1", "SEP-1")]:
        _link(g, a, b, E.FLOWS_TO)
    for v in ["W01.MV", "W01.DHSV"]:
        _link(g, "SIS-W01", v, E.ACTUATES)

    # ---------------------------------------------------------------- instrumentation
    tmap = yaml.safe_load(Path(tag_map_path).read_text())
    _add(g, Node(id="TWIN-W01", type=N.SIMULATION_MODEL, name="W01 well-integrity digital twin",
                 props=dict(model_type="physics surrogate", version="1.0.0", code="digital_twin/",
                            valid_choke_64=[8, 96], valid_T_A_C=[20, 90],
                            calibrated_on="EVT-W01-BLEED-2026-01")))
    _add(g, Node(id="TWIN-PROD-OLGA", type=N.SIMULATION_MODEL,
                 name="Production-network multiphase model (assumed to exist at the operator)",
                 props=dict(model_type="dynamic multiphase", status="adapter stub")))
    _link(g, "TWIN-PROD-OLGA", "FL-W01", E.ESTIMATES, scope="flowline and network")
    tests_recording = {}
    for t in tmap["tags"]:
        sig = dict(unit=t["unit"], twin_signal=t["twin_signal"], kind=t["kind"])
        for k in ("sigma", "rel_sigma", "resolution"):
            if k in t:
                sig[k] = t[k]
        if t["kind"] == "virtual":
            tgt = t["estimates"]
            _add(g, Node(id=t["external_id"], type=N.VIRTUAL_TAG, name=t["external_id"], props=sig))
            _link(g, "TWIN-W01", t["external_id"], E.PRODUCES)
            _link(g, t["external_id"], tgt["node"], E.ESTIMATES, property=tgt["property"],
                  location=tgt["location"])
            continue
        tgt = t["measures"]
        _add(g, Node(id=t["external_id"], type=N.TAG, name=t["external_id"], props=sig))
        _link(g, t["external_id"], tgt["node"], E.MEASURES, property=tgt["property"], location=tgt["location"])
        if t["kind"] == "measured":
            if t["sensor"] not in g:
                _add(g, Node(id=t["sensor"], type=N.SENSOR, name=f"Sensor {t['sensor'][4:]}",
                             props=dict(calibrated="2025-11-01")))
                _link(g, t["sensor"], t["installed_on"], E.INSTALLED_ON)
            _link(g, t["external_id"], t["sensor"], E.PRODUCED_BY)
            if t["external_id"] in ("W01-ZT-CHK", "W01-FL-PT", "W01-PT-WH", "W01-TT-WH"):
                _link(g, "TWIN-W01", t["external_id"], E.CONSUMES)
        else:
            tests_recording.setdefault(t["recorded_by"], []).append(t["external_id"])

    # ---------------------------------------------------------------- twin parameters
    for pid, name, desc, path, kind, a, b, unit in C.PARAMETERS:
        prior = (f"U({a}, {b})" if kind == "uniform" else
                 f"nominal x exp(N(0, {a}))" if kind == "lognormal" else "known only at last inspection")
        _add(g, Node(id=pid, type=N.MODEL_PARAMETER, name=name,
                     props=dict(twin_path=path, prior=prior, prior_kind=kind, unit=unit)))
        _link(g, "TWIN-W01", pid, E.HAS_PARAMETER)
        _link(g, pid, desc, E.DESCRIBES)

    # ---------------------------------------------------------------- failure mechanisms
    sigs = yaml.safe_load(Path(signatures_path).read_text())["mechanisms"] if Path(signatures_path).exists() else {}
    for mid, (name, owner, iso, connects, spec, physics) in C.MECHANISMS.items():
        props = dict(iso14224_class=iso, physics=physics, simulated=spec is not None)
        if spec is not None:
            props["twin_fault"] = f"{spec[0]}({', '.join(f'{k}={v}' for k, v in spec[1].items())})"
            props["bleed_annulus"] = spec[2]
        if mid in sigs:
            props["signature"] = {k: v for k, v in sigs[mid].items() if k not in ("twin_fault", "bleed_annulus")}
        _add(g, Node(id=mid, type=N.FAILURE_MECHANISM, name=name, props=props))
        _link(g, owner, mid, E.HAS_MECHANISM)
        for node, role in connects:
            _link(g, mid, node, E.CONNECTS, role=role)
        if spec is not None:
            _link(g, "TWIN-W01", mid, E.SIMULATES, fault=props["twin_fault"])

    # ---------------------------------------------------------------- tests
    for tid, (name, cls, cost, online, dur, uses, ev, mon) in C.TESTS.items():
        spec = TestSpec(reliability=cls, cost_nok=cost, online=online, duration_h=dur, description=name)
        props = spec.model_dump()
        if tid in C.TEST_PREDICTS:
            props["predicts"] = [k for k, _ in C.TEST_PREDICTS[tid]]
            props["requires_bleed_of"] = [a for _, a in C.TEST_PREDICTS[tid]]
        _add(g, Node(id=tid, type=N.TEST, name=name, props=props))
        for tag in uses:
            _link(g, tid, tag, E.USES)
        for m in ev:
            _link(g, tid, m, E.EVIDENCE_FOR)
    for tid, tags in tests_recording.items():
        for tag in tags:
            _link(g, tag, tid, E.PRODUCED_BY)

    # ---------------------------------------------------------------- risk view
    for fid, (name, obs) in C.FAILURE_MODES.items():
        _add(g, Node(id=fid, type=N.FAILURE_MODE, name=name, props=dict(observed_as=obs)))
    for tid, (*_, mon) in C.TESTS.items():
        for f in mon:
            _link(g, tid, f, E.MONITORS)
    for bid, (name, norsok, members) in C.ENVELOPES.items():
        _add(g, Node(id=bid, type=N.BARRIER_ENVELOPE, name=name, props=dict(norsok_well_barrier=norsok)))
        for item, section in members:
            _link(g, bid, item, E.IMPLEMENTED_BY, section=section)
    for hid, name in C.HAZARDS.items():
        _add(g, Node(id=hid, type=N.HAZARD, name=name))
    for m, f, cond in C.CAUSES:
        _link(g, m, f, E.CAUSES, condition=cond)
    for v, f, why in C.MANIFESTS:
        _link(g, v, f, E.MANIFESTS_IN, note=why)
    for f, b, how in C.DEGRADES:
        _link(g, f, b, E.DEGRADES, how=how)
    for b, h in C.BARRIER_HAZARD:
        _link(g, b, h, E.LEADS_TO)
    for f, h, why in C.DIRECT_HAZARD:
        _link(g, f, h, E.LEADS_TO, why=why)
    for a, b, why in C.AGGRAVATES:
        _link(g, a, b, E.AGGRAVATES, why=why)

    for lid, d in C.LIMITS.items():
        d = dict(d)
        vol, lim_by = d.pop("volume"), d.pop("limited_by")
        spec = LimitSpec(**d)
        _add(g, Node(id=lid, type=N.LIMIT, name=f"{spec.kind} {vol[4:]} rev {spec.revision}"
                     + (" (superseded)" if spec.superseded_by else ""), props=spec.model_dump()))
        _link(g, lid, vol, E.APPLIES_TO, active=spec.superseded_by is None)
        for it in lim_by:
            _link(g, lid, it, E.LIMITED_BY)
        if spec.superseded_by is None:
            _link(g, "FM.MAASP." + vol[-1], lid, E.CHECKED_AGAINST, tier=spec.kind)

    pid, pname, pprops, governs = C.POLICY
    _add(g, Node(id=pid, type=N.DECISION_POLICY, name=pname, props=pprops))
    for f in governs:
        _link(g, pid, f, E.GOVERNS)
    return g


# -------------------------------------------------------------------------------- validation
def validate(g: nx.MultiDiGraph) -> list[str]:
    """Structural rules. Returns a list of violations (empty = valid)."""
    errs = []
    T = lambda n: g.nodes[n]["type"]
    out = lambda n, e: [v for _, v, k in g.out_edges(n, keys=True) if k == e.value]
    inn = lambda n, e: [u for u, _, k in g.in_edges(n, keys=True) if k == e.value]
    hazards = {n for n in g if T(n) == N.HAZARD.value}
    for n in g:
        t = T(n)
        if t == N.FAILURE_MECHANISM.value:
            owners = inn(n, E.HAS_MECHANISM)
            if len(owners) != 1 or T(owners[0]) not in (N.MAINTAINABLE_ITEM.value, N.SENSOR.value):
                errs.append(f"R1 {n}: must belong to exactly one maintainable item or sensor")
            if not out(n, E.CAUSES):
                errs.append(f"R2 {n}: causes no failure mode")
            if not inn(n, E.EVIDENCE_FOR):
                errs.append(f"R3 {n}: no test can reveal it")
        if t == N.MAINTAINABLE_ITEM.value and not out(n, E.HAS_MECHANISM):
            errs.append(f"R4 {n}: maintainable item without failure mechanism")
        if t == N.FAILURE_MODE.value:
            reach = nx.descendants(g, n)
            if not reach & hazards:
                errs.append(f"R5 {n}: no path to a hazard")
            if not inn(n, E.CAUSES) and not inn(n, E.MANIFESTS_IN):
                errs.append(f"R6 {n}: nothing causes it")
        if t == N.TAG.value and not out(n, E.MEASURES):
            errs.append(f"R7 {n}: tag measures nothing")
        if t == N.TEST.value and not (out(n, E.EVIDENCE_FOR) or out(n, E.MONITORS)):
            errs.append(f"R8 {n}: test gives no evidence")
    for v in [n for n in g if T(n) == N.CONTAINMENT_VOLUME.value and n != "W01.BORE"]:
        maasp = [l for l in inn(v, E.APPLIES_TO)
                 if g.nodes[l]["kind"] == "MAASP" and not g.nodes[l].get("superseded_by")]
        if len(maasp) != 1:
            errs.append(f"R9 {v}: needs exactly one active MAASP, has {maasp}")
    return errs


def export_json(g: nx.MultiDiGraph, path: Path = HERE / "kg.json") -> Path:
    data = nx.node_link_data(g, edges="edges")
    path.write_text(json.dumps(data, indent=1, default=str))
    return path


if __name__ == "__main__":
    G = build_graph()
    print(f"nodes={G.number_of_nodes()} edges={G.number_of_edges()} schema={G.graph['schema_version']}")
    from collections import Counter
    print(dict(Counter(d["type"] for _, d in G.nodes(data=True))))
    print("validation:", validate(G) or "OK")
    print("snapshot:", export_json(G).name)
